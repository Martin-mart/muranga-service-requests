/**
 * Generates src/styles/icons.css: the Boxicons @font-face (WOFF2 only) plus
 * ONLY the glyph classes the app references. The full boxicons.css is ~70 KB
 * of CSS and ~2.7 MB of fonts in five formats; this keeps the precached app
 * shell small for low-bandwidth users.
 *
 * Run after adding/removing an icon:  npm run icons
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const srcDir = join(root, 'src');
const boxicons = readFileSync(join(root, 'node_modules/boxicons/css/boxicons.css'), 'utf8');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : /\.(tsx?|ts)$/.test(name) ? [path] : [];
  });
}

const used = new Set();
for (const file of walk(srcDir)) {
  for (const match of readFileSync(file, 'utf8').matchAll(/['"`](bx[sl]?-[a-z0-9-]+)['"`]/g)) {
    used.add(match[1]);
  }
}

const rules = [];
const missing = [];
for (const name of [...used].sort()) {
  const rule = new RegExp(`\\.${name}:before\\s*\\{\\s*content:\\s*"([^"]+)";?\\s*\\}`).exec(
    boxicons,
  );
  if (rule) rules.push(`.${name}::before {\n  content: '${rule[1]}';\n}`);
  else missing.push(name);
}
if (missing.length > 0) {
  console.error(`Unknown Boxicons classes: ${missing.join(', ')}`);
  process.exit(1);
}

const css = `/* GENERATED by scripts/build-icons.mjs. Do not edit; run \`npm run icons\`. */
@font-face {
  font-family: boxicons;
  font-weight: 400;
  font-style: normal;
  font-display: block;
  src: url('../../node_modules/boxicons/fonts/boxicons.woff2') format('woff2');
}

.bx {
  display: inline-block;
  font-family: boxicons !important;
  font-weight: 400;
  font-style: normal;
  font-variant: normal;
  line-height: 1;
  text-rendering: auto;
  text-transform: none;
  speak: never;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules.join('\n\n')}
`;
writeFileSync(join(srcDir, 'styles/icons.css'), css);
process.stdout.write(`icons.css: ${rules.length} glyphs\n`);
